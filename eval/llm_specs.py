def run_llm_analysis():
    ver = AR.tf_version()
    tf = AR.load_tf()
    nlp = tf.load_model("en_core_web_md")
    nlp.max_length = 5_000_000
    extra, phrase_ids = SB.phrase_setup(tf)
    done, old_f = {}, defaultdict(list)
    if TABLE.exists():
        for line in TABLE.read_text(encoding="utf-8").splitlines():
            r = json.loads(line)
            done[r["id"]] = r
    if FINDINGS.exists():
        for line in FINDINGS.read_text(encoding="utf-8").splitlines():
            f = json.loads(line)
            old_f[f["id"]].append(f)
    recs = load_docs()
    TMP.mkdir(parents=True, exist_ok=True)
    rows, allf = [], []
    t0, n_new = time.monotonic(), 0
    for i, rec in enumerate(recs, 1):
        _, kept, _, _, _ = kept_text(rec)
        key = (ver["sha256"], SB.sha16(kept))
        r = done.get(rec["id"])
        if r and (r["tf_sha256"], r["mask_sha"]) == key:
            rows.append(r)
            allf.extend(old_f[rec["id"]])
            continue
        tmp = TMP / (rec["id"] + ANALYSE_AS)
        tmp.write_text(kept, encoding="utf-8")
        t1 = time.monotonic()
        try:
            fs, st = tf.analyse(str(tmp), nlp, None, extra, set())
        finally:
            tmp.unlink()
        rows.append({"id": rec["id"], "tf_sha256": ver["sha256"],
                     "mask_sha": key[1], "words": st["words"],
                     "tf_masked_pct": st["masked_pct"],
                     "seconds": round(time.monotonic() - t1, 2),
                     "counts": AB.counts_of(fs, phrase_ids)})
        allf.extend(SB.finding_rec(f, id=rec["id"]) for f in fs)
        n_new += 1
        print(f"  {i}/{len(recs)} {st['words']:,} words, "
              f"{time.monotonic() - t0:.0f}s", file=sys.stderr, flush=True)
    TABLE.write_text("".join(json.dumps(r) + "\n" for r in rows),
                     encoding="utf-8")
    FINDINGS.write_text("".join(json.dumps(f) + "\n" for f in allf),
                        encoding="utf-8")
    try:
        TMP.rmdir()
    except OSError:
        pass
    print(f"analysed {n_new} files ({len(rows) - n_new} up to date), "
          f"{time.monotonic() - t0:.0f}s", file=sys.stderr)


def load_llm(sha):
    recs = load_docs()
    by = {}
    for line in TABLE.read_text(encoding="utf-8").splitlines():
        r = json.loads(line)
        if r["tf_sha256"] == sha:
            by[r["id"]] = r
    missing = [r["id"] for r in recs if r["id"] not in by]
    if missing:
        sys.exit(f"table lacks {len(missing)} files for ticfinder {sha}; "
                 "run analyse")
    return [by[r["id"]] for r in sorted(recs, key=lambda r: r["id"])]


class LBoot:
    """Document bootstrap for the LLM corpus, seed 12012."""

    def __init__(self, rows, draws, seed):
        import numpy as np
        self.np, self.rows = np, rows
        rng = np.random.default_rng(seed)
        self.idx = rng.integers(0, len(rows), size=(draws, len(rows)))
        self.W = np.array([r["words"] for r in rows], dtype=float)
        self.Wd = self.W[self.idx].sum(axis=1)

    def stat(self, lvl, key):
        np = self.np
        c = np.array([r["counts"].get(lvl, {}).get(key, 0)
                      for r in self.rows], dtype=float)
        d = c[self.idx].sum(axis=1) / self.Wd * 1000
        return {"n": int(c.sum()), "docs": int((c > 0).sum()),
                "rate": c.sum() / self.W.sum() * 1000, "ci": AB.pct(d),
                "draws": d}


def logvar(d):
    import numpy as np
    with np.errstate(divide="ignore", invalid="ignore"):
        x = np.log(d)
    x = x[np.isfinite(x)]
    return float(np.var(x, ddof=1)) if len(x) > 1 else math.inf


def pin_checks(MB, AX, keys):
    """The rebuilt pool and arXiv bootstraps against the TF-010 JSON."""
    out = []
    sj = json.loads(SPEC_JSON.read_text(encoding="utf-8"))
    ok = bad = 0
    for r in sj["rows"]:
        if r["table"] not in ("Rates: construction", "Rates: pattern"):
            continue
        P = MB.stat(r["level"], r["key"])["pool"]["equal"]
        got = AB.sig4({"rate": float(P["rate"]), "rate_lo": float(P["ci"][0]),
                       "rate_hi": float(P["ci"][1])})
        ok, bad = (ok + 1, bad) if got == r["pool_equal"] else (ok, bad + 1)
    out.append(f"pool equal-weight rows equal to TF-010 JSON: {ok} of "
               f"{ok + bad}")
    aj = json.loads(ARXIV_JSON.read_text(encoding="utf-8"))
    ok = bad = 0
    for r in aj["rows"]:
        if r["table"] not in ("Rates per text type: all, construction",
                              "Rates per text type: all, pattern"):
            continue
        s = AX.stat("all", r["level"], r["key"])
        got = AB.sig4({"ratio": float(s["ratio"]),
                       "lo": float(s["ratio_ci"][0]),
                       "hi": float(s["ratio_ci"][1])})
        want = {"ratio": r["ratio"], "lo": r["ratio_lo"], "hi": r["ratio_hi"]}
        ok, bad = (ok + 1, bad) if got == want else (ok, bad + 1)
    out.append(f"arXiv all-section ratio rows equal to TF-010 JSON: {ok} of "
               f"{ok + bad}")
    return out


def boots():
    """The three bootstraps of the TF-012 joint draw, from the pinned
    tables: the pool (seed 9009), arXiv (seed 8008) and the LLM corpus
    (seed 12012)."""
    SB.use_tables(str(POOL_TABLES), str(ARXIV_TABLES), ARXIV_SHA)
    ver, _, _, by, author, arxiv_pre = SB.load_tables()
    groups = {**{s: by[s] for s in SB.SOURCES}, "arxiv": arxiv_pre,
              "author": author}
    MB = SB.MBoot(groups, DRAWS, POOL_SEED)
    AB.use_paths(str(ARXIV_TABLES), "full")
    _, arows, _ = AB.load_body_table(ARXIV_SHA)
    AX = AB.Boot(arows, DRAWS, ARXIV_SEED)
    llm = load_llm(ver["sha256"])
    LB = LBoot(llm, DRAWS, LLM_SEED)
    return ver, by, groups, MB, arows, AX, llm, LB


def build_rows():
    """Every construction and pattern row with at least MIN_N findings in
    the LLM corpus or the pool, with rates, LRs and the arXiv prior."""
    import numpy as np
    ver, by, groups, MB, arows, AX, llm, LB = boots()
    pat_of = defaultdict(set)
    for rs in [*groups.values(), llm, arows["pre"], arows["post"]]:
        for r in rs:
            cnt = r["counts"].get("all", r["counts"])
            for k in cnt.get("pattern", {}):
                pat_of[k.split("|")[0]].add(k)
    keys = {lvl: sorted({k for r in llm for k in r["counts"].get(lvl, {})}
                        | {k for s in SB.SOURCES for r in by[s]
                           for k in r["counts"].get(lvl, {})})
            for lvl in LR_LEVELS}
    rows = []
    for lvl in LR_LEVELS:
        for k in keys[lvl]:
            if lvl == "pattern" and pat_of[k.split("|")[0]] == {k}:
                continue
            L = LB.stat(lvl, k)
            s = MB.stat(lvl, k)
            P, U = s["pool"], s["g"]["author"]
            if L["n"] < MIN_N and P["n"] < MIN_N:
                continue
            row = {"level": lvl, "key": k, "llm": L,
                   "pool": {"n": P["n"], **P[SB.POOL]}, "author": U,
                   "flag": k.split("|")[0] == FLAGGED}
            if L["n"] >= MIN_N and P["n"] >= MIN_N:
                r, ci = SB.ratio(L["rate"], row["pool"]["rate"], L["draws"],
                                 row["pool"]["draws"])
                with np.errstate(divide="ignore", invalid="ignore"):
                    row["lr_draws"] = L["draws"] / row["pool"]["draws"]
                row.update(lr=r, lr_ci=ci, lr_var=logvar(row["lr_draws"]))
            if L["n"] >= MIN_N and U["n"] >= MIN_N:
                r, ci = SB.ratio(L["rate"], U["rate"], L["draws"],
                                 U["draws"])
                row.update(lr_author=r, lr_author_ci=ci)
            a = AX.stat("all", lvl, k)
            row["ax_n"] = (a["o"]["pre"]["n"], a["o"]["post"]["n"])
            if min(row["ax_n"]) >= MIN_N:
                row.update(ax=a["ratio"], ax_ci=a["ratio_ci"],
                           ax_var=logvar(a["ratio_draws"]))
            rows.append(row)
    shrink(rows)
    return ver, rows, MB, AX, len(llm), int(LB.W.sum()), pin_checks(MB, AX,
                                                                     keys)


def shrink(rows):
    """Normal-normal empirical Bayes on the log scale. For a row with an LR
    and an arXiv prior: y = log LR with bootstrap variance s2, prior mean
    m = log arXiv post over pre with bootstrap variance a2. Across rows,
    E[(y - m)^2] = tau2 + s2 + a2, so the method-of-moments estimate is
    tau2 = max(0, mean((y - m)^2 - s2 - a2)). The prior for a row is
    N(m, tau2 + a2), and the posterior mean is m + w (y - m) with
    w = (tau2 + a2) / (tau2 + a2 + s2)."""
    use = [r for r in rows if "lr" in r and "ax" in r
           and math.isfinite(r["lr_var"]) and math.isfinite(r["ax_var"])
           and r["lr"] > 0 and r["ax"] > 0]
    d = [(math.log(r["lr"]) - math.log(r["ax"])) ** 2 - r["lr_var"]
         - r["ax_var"] for r in use]
    tau2 = max(0.0, sum(d) / len(d)) if d else math.nan
    for r in use:
        y, m = math.log(r["lr"]), math.log(r["ax"])
        v = tau2 + r["ax_var"]
        w = v / (v + r["lr_var"])
        r["w"] = w
        r["lr_shrunk"] = math.exp(m + w * (y - m))
    off = [math.log(r["lr"]) - math.log(r["ax"]) for r in use]
    shrink.info = {"rows": len(use), "tau2": tau2,
                   "mean_offset": sum(off) / len(off) if off else math.nan}


