def pacino():
    p = os.environ.get("PACINO")
    if not p or not Path(p).is_dir():
        sys.exit("PACINO is not set; source tools/setup.sh")
    return Path(p)


def git(*a, text=True):
    r = subprocess.run(["git", "-C", str(pacino()), *a], capture_output=True,
                       text=text)
    if r.returncode:
        sys.exit(f"git {' '.join(a)}: {r.stderr.strip()}")
    return r.stdout


# --------------------------------------------------------------- survey

def classify(path, raw):
    """(kept, reason) for one candidate file at the pin."""
    if path in DROP:
        return False, DROP[path]
    if path in KEEP_FILES or path.startswith(KEEP_DIRS):
        return True, "kept"
    if path.startswith(PLACEHOLDER_DIRS) and "placeholder:start" in raw:
        return False, "generated placeholder page"
    return False, "not on the approved list"


def cmd_survey(args):
    head = git("rev-parse", "HEAD").strip()
    print(f"$PACINO HEAD {head}; corpus pin {PIN}"
          + ("" if head == PIN else "  (HEAD has moved; reading the pin)"))
    files = [f for f in git("ls-tree", "-r", "--name-only", PIN,
                            *[r.rstrip("/") for r in ROOTS]).splitlines()
             if f.lower().endswith(SUFFIXES)]
    recs, why = [], Counter()
    TEXT.mkdir(parents=True, exist_ok=True)
    for f in sorted(files):
        raw = git("show", f"{PIN}:{f}")
        keep, reason = classify(f, raw)
        w = len(raw.split())
        if not args.quiet:
            print(f"{w:7d}  {'keep' if keep else 'drop'}  {f}"
                  + ("" if keep else f"  ({reason})"))
        if not keep:
            why[reason] += w
            continue
        i = SB.doc_id("pacino", f)
        (TEXT / f"{i}.md").write_text(raw, encoding="utf-8")
        recs.append({"id": i, "path": f, "raw_words": w,
                     "file": f"text/{i}.md", "sha": SB.sha16(raw)})
    got = (len(recs), sum(r["raw_words"] for r in recs))
    print(f"\ncandidates {len(files)}; kept {got[0]} files, {got[1]:,} raw "
          "words; dropped: " + ", ".join(f"{k} {v:,}"
                                         for k, v in why.most_common()))
    if got != WANT_KEPT:
        sys.exit(f"kept list differs from the approved one {WANT_KEPT}")
    DOCS.write_text("".join(json.dumps(r) + "\n" for r in recs),
                    encoding="utf-8")
    print(f"wrote {DOCS.relative_to(AR.ROOT)} and {len(recs)} texts")


