def lr_cell(r, k="lr"):
    return (SB.ci_txt(r[k], r[k + "_ci"]) if k in r else "-")


def print_table(rows):
    for lvl in LR_LEVELS:
        print(f"\n{lvl:40s} {'LLM n':>6} {'pool n':>6} {'LR (95% CI)':>24} "
              f"{'arXiv':>6} {'shrunk':>7} {'w':>5} {'vs author':>7}")
        rs = sorted((r for r in rows if r["level"] == lvl),
                    key=lambda r: -r.get("lr", -1))
        for r in rs:
            print(f"{r['key'][:40]:40s} {r['llm']['n']:6d} "
                  f"{r['pool']['n']:6d} {lr_cell(r):>24} "
                  f"{fmt(r.get('ax')):>6} {fmt(r.get('lr_shrunk')):>7} "
                  f"{fmt(r.get('w')):>5} {fmt(r.get('lr_author')):>7}"
                  + ("  *" if r["flag"] else ""))


def hypotheses(rows):
    lr = [r for r in rows if "lr" in r]
    h2 = [r for r in lr if "ax" in r and r["ax_ci"][0] > 1]
    h2y = [r for r in h2 if r["lr"] > 1]
    h3 = [r for r in lr if "lr_author" in r]
    h3y = [r for r in h3 if (r["lr"] > 1) == (r["lr_author"] > 1)]
    above = [r for r in lr if r["lr_ci"][0] > 1]
    below = [r for r in lr if r["lr_ci"][1] < 1]
    inside = [r for r in lr if r["lr_ci"][0] <= 1 <= r["lr_ci"][1]]
    return {"h2": (h2, h2y), "h3": (h3, h3y),
            "h4": (lr, above, inside, below)}


def print_checks(rows):
    H = hypotheses(rows)
    h2, h2y = H["h2"]
    print(f"\nH2: {len(h2y)} of {len(h2)} rows whose arXiv interval lies above"
          f" 1 have LR above 1; misses: "
          + ", ".join(f"{r['key']} {r['lr']:.2f}" for r in h2
                      if r not in h2y))
    h3, h3y = H["h3"]
    print(f"H3: {len(h3y)} of {len(h3)} rows on the same side of 1 against "
          "the author's specs; differ: "
          + ", ".join(f"{r['key']} {r['lr']:.2f}/{r['lr_author']:.2f}"
                      for r in h3 if r not in h3y))
    lr, above, inside, below = H["h4"]
    print(f"H4: of {len(lr)} LR rows, {len(above)} above 1, {len(inside)} "
          f"contain 1, {len(below)} below 1")
    small = [r for r in lr if "lr_shrunk" in r
             and min(r["llm"]["n"], r["pool"]["n"]) < SMALL_N]
    if small:
        mv = [abs(math.log(r["lr_shrunk"] / r["lr"])) for r in small]
        print(f"shrinkage, rows under {SMALL_N} findings: {len(small)}, "
              f"median move x{math.exp(SB.median(mv)):.2f}, max "
              f"x{math.exp(max(mv)):.2f}")


def show_sample(key, n):
    """Console only: n random LLM-corpus findings for a construction or a
    CID|pattern key."""
    pool = []
    for line in FINDINGS.read_text(encoding="utf-8").splitlines():
        f = json.loads(line)
        if key in (f["construction"], f"{f['construction']}|{f['pattern']}"):
            pool.append(f)
    rng = random.Random(f"{LLM_SEED}-check-{key}")
    pick = rng.sample(pool, min(n, len(pool)))
    print(f"\n=== {key}: {len(pick)} of {len(pool)}")
    for i, f in enumerate(pick, 1):
        print(f"\n[{i}] {f['label']}\n  MATCH: {f['text']}\n  "
              f"SENT:  {' '.join(f['context'].split())[:400]}")


