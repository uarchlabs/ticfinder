def load_docs():
    if not DOCS.exists():
        sys.exit("no docs.jsonl; run survey")
    return [json.loads(x) for x in DOCS.read_text(encoding="utf-8")
            .splitlines()]


def kept_text(rec, tf=None):
    raw = (OUT / rec["file"]).read_text(encoding="utf-8")
    kept, cats = mask_llm(raw)
    final, st = None, {}
    if tf is not None:
        final = tf.mask_markdown(kept, st, tf.CODE_MASK,
                                 markdown=ANALYSE_AS == ".md")
    return raw, kept, cats, final, st


def mask_summary(tf):
    rows = []
    for r in load_docs():
        raw, kept, cats, final, st = kept_text(r, tf)
        n0 = SB.nonws(raw) or 1
        rows.append({"id": r["id"], "path": r["path"],
                     "raw_words": r["raw_words"],
                     "words": len(re.findall(r"[A-Za-z]+", final)),
                     "excl_pct": 100 * (n0 - SB.nonws(kept)) / n0,
                     "pct": 100 * (n0 - SB.nonws(final)) / n0,
                     "cats": cats, "tf_md": st["md_masked_chars"],
                     "tf_code": st["code_masked_chars"], "n0": n0,
                     "final": final})
    return rows


def cmd_mask_report(args):
    tf = AR.load_tf()
    rows = mask_summary(tf)
    pct = [x["pct"] for x in rows]
    tot0 = sum(x["n0"] for x in rows) or 1
    cats = Counter()
    for x in rows:
        cats.update(x["cats"])
    cats["ticfinder markdown rules"] = sum(x["tf_md"] for x in rows)
    cats["ticfinder code masker"] = sum(x["tf_code"] for x in rows)
    if args.files:
        print("masked%  excl%   words  file")
        for x in sorted(rows, key=lambda x: -x["pct"]):
            print(f"{x['pct']:6.1f}  {x['excl_pct']:5.1f}  {x['words']:6d}  "
                  f"{x['path']}")
        print()
    print(f"=== pacino LLM specs: {len(rows)} files, raw words "
          f"{sum(x['raw_words'] for x in rows):,}, kept words "
          f"{sum(x['words'] for x in rows):,}")
    print(f"  masked share (all layers): median {SB.median(pct):.1f}%, "
          f"min {min(pct):.1f}%, max {max(pct):.1f}%; over 40%: "
          f"{sum(p > 40 for p in pct)}; over 60%: {sum(p > 60 for p in pct)}"
          f"; exclusions alone median "
          f"{SB.median([x['excl_pct'] for x in rows]):.1f}%")
    print("  blanked non-space chars by rule (share of raw): " + ", ".join(
        f"{k} {100 * v / tot0:.1f}%" for k, v in cats.most_common() if v))
    print(f"  files with under 100 kept words: "
          f"{sum(x['words'] < 100 for x in rows)}")
    hits, pool = Counter(), []
    for x in rows:
        for s in AB.sentences(x["final"], 0, len(x["final"])):
            pool.append(s)
            for k, rx in RESIDUE.items():
                if rx.search(s):
                    hits[k] += 1
    print(f"  residue scan over {len(pool):,} sentences: " + (", ".join(
        f"{k} {v} ({100 * v / max(len(pool), 1):.2f}%)"
        for k, v in hits.items()) or "no hits"))
    if args.residue:
        rx = RESIDUE[args.residue]
        for s in [s for s in pool if rx.search(s)][:args.n]:
            print(f"  [{args.residue}] {s[:300]}")
    if not args.quiet:
        rng = random.Random(f"{SPOT_SEED}-spot")
        pick = rng.sample(pool, min(args.n, len(pool)))
        print(f"\n  --- {len(pick)} random masked sentences; console only")
        for i, s in enumerate(pick, 1):
            print(f"  [{i}] {s}")


