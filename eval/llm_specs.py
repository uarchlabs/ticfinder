#
# The pool's markdown exclusions (Rust RFCs and OpenTitan: YAML front
# matter, link definitions, comments, headings, pipe tables, link brackets)
# then the pacino additions below. ticfinder's own masking runs after, on
# the kept text analysed as ANALYSE_AS.

FRONT = re.compile(r"\A---\n.*?\n---[ \t]*\n", re.S)
# An HTML tag that spans lines: ticfinder blanks single-line tags only.
HTML_MULTI = re.compile(r"<[A-Za-z][\w-]*(?:\s[^<>]*)?\n[^<>]*>")
# Raw HTML blocks whose content is not prose.
HTML_BLOCK = re.compile(r"<(style|script|svg)\b.*?(?:</\1\s*>|\Z)",
                        re.S | re.I)
# mkdocs admonition and details markers; the indented body stays.
ADMON = re.compile(r"^ {0,3}(?:!!!|\?\?\?\+?)[ \t]*\w[^\n]*$", re.M)
# Port and parameter declarations and assignments outside fences: a whole
# line `name : input logic ...`, `NAME[0:4]  : int  ...` or `name = value`.
# A space before the colon separates a declaration from a prose label.
DECL = re.compile(
    r"^[ \t]*[A-Za-z_][\w]*(?:\[[^\]\n]*\])*[ \t]+:[ \t]*(?:"
    r"(?:input|output|inout)[ \t]+[\w\[]"
    r"|(?:int|integer|logic|bit|unsigned|signed)(?=[ \t]*(?:$|\[|--|[ \t]{2})))"
    r"[^\n]*$", re.M)
ASSIGN = re.compile(r"^[ \t]*[A-Za-z_][\w.\[\]]*[ \t]*=[ \t]*[\w'.\[\]+-]+"
                    r"[ \t]*;?[ \t]*$", re.M)
# The kept text is analysed as plain text (user, TF-012 requirement 4): the
# decision registries hang-indent each entry's prose, which ticfinder's
# markdown-only indented-code rule would blank as code.
ANALYSE_AS = ".txt"


def mask_llm(text):
    b = SB.Blanker(text)
    m = FRONT.match(text)
    if m:
        b.blank(0, m.end(), "header")
    SB.mask_md_common(b, text)
    for m in HTML_BLOCK.finditer(text):
        b.blank(m.start(), m.end(), "html blocks")
    for m in HTML_MULTI.finditer(text):
        b.blank(m.start(), m.end(), "html tags")
    for m in ADMON.finditer(text):
        b.blank(m.start(), m.end(), "admonition markers")
    for rx in (DECL, ASSIGN):
        for m in rx.finditer(text):
            b.blank(m.start(), m.end(), "declarations")
    return b.text(), b.cats


